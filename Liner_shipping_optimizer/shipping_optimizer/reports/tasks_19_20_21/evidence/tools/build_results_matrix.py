"""Build ``results_matrix.md`` and ``experiment_manifest.json`` from the recorded evidence.

Every row comes from a file under ``evidence/outputs`` (controlled runs), ``evidence/runs``
(orchestrator runs: ``*.pipeline_output.json`` + ``*.meta.txt``); nothing is typed by hand.

usage: python -I build_results_matrix.py <report_dir> [--exclude-tag TAG ...]
"""
import glob
import hashlib
import json
import os
import re
import statistics
import sys
from pathlib import Path

REPORT = Path(sys.argv[1])
EV = REPORT / "evidence"
excluded = set()
if "--exclude-tag" in sys.argv:
    i = 0
    args = sys.argv
    while i < len(args):
        if args[i] == "--exclude-tag":
            excluded.add(args[i + 1])
            i += 1
        i += 1


def sha(path: Path) -> str:
    h = hashlib.sha256()
    h.update(path.read_bytes())
    return h.hexdigest()


def m(x, nd=2):
    return "" if x is None else f"{x / 1e6:.{nd}f}"


def pct(x, nd=1):
    return "" if x is None else f"{x:.{nd}f}"


def num(x, fmt=",.0f"):
    return "" if x is None else format(x, fmt)


lines = ["# Results matrix — every recorded run and seed", "",
         "Generated by `evidence/tools/build_results_matrix.py` from the files named in each row; nothing is typed by "
         "hand. USD figures are the **independent ledger's** weekly values (M = million). `solver` is the global-stage "
         "backend of the run (`cbc` = production default, `highs` = opt-in, experimental).", ""]

# ----------------------------------------------------------------------------- A: controlled
ctl = []
for f in sorted(glob.glob(str(EV / "outputs" / "*.json"))):
    name = Path(f).stem
    try:
        d = json.loads(Path(f).read_text(encoding="utf-8"))
    except Exception:                                                  # noqa: BLE001
        continue
    if not isinstance(d, dict) or "runs" not in d or "seed" not in d or "iterations" in d:
        continue
    parts = name.split("_")
    if len(parts) < 4 or not parts[1].startswith("seed"):
        continue
    tag, var, solver_tl = parts[0], parts[2], parts[-1]
    if tag in excluded:
        continue
    for r in d["runs"]:
        led = r.get("ledger") or {}
        s = r.get("solver") or {}
        sr = r.get("strategy_report") or {}
        util = (sr.get("utilisation") or {}).get("network") or {}
        fr = (led.get("reconciliation") or {}).get("flow_reoptimisation") or {}
        ctl.append(dict(
            tag=tag, seed=d["seed"], variant=var, solver=("highs" if "highs" in solver_tl else "cbc"),
            tl=d.get("time_limit_sec"), strategy=r.get("strategy"), status=r.get("status"),
            sol=s.get("solution_status"), profit=led.get("profit"), rev=led.get("revenue"),
            cost=led.get("total_cost"), margin=led.get("margin_pct"), teu=led.get("served_teu"),
            cov=led.get("coverage_pct"), svc=led.get("services"), ves=led.get("vessels"),
            lf=util.get("load_factor"), paths=r.get("paths_total"), vars=s.get("variables"),
            gap=s.get("gap_to_bound_pct"), viol=len(led.get("violations", [])),
            recon=(led.get("reconciliation") or {}).get("reconciled"),
            reopt=fr.get("gain_usd"), pool=(d.get("pool") or {}).get("unique_order_sha256", "")[:10],
            pathsha=(r.get("path_pool_sha256") or "")[:10], build=(r.get("path_model") or {}).get("path_build_sec"),
            solve=s.get("runtime_sec"), file=Path(f).name))
NOTES = {
    "M6": "DEGRADED MACHINE: 18 of 40 runs `not_solved` for models that solve in M5; NOT used for any claim "
          "(the repair triggers it shows are listed separately in task20_path_selection.md §7)",
    "M1": "first cost-aware batch (tree ctl1); stopped before CMALL / CAMALL",
    "M1b": "stopped early (tree ctl2): B0, H3, FA complete",
    "M2": "HiGHS 300 s, opt-in / experimental, tree ctl3",
    "M8": "HiGHS 300 s, opt-in / experimental, final tree",
    "M11": "HiGHS 600 s long-budget REFERENCE, opt-in / experimental, final tree",
    "M4": "hold-out seeds 5-9, tree ctl3",
    "M5": "tree ctl4 (re-routing never serves less than the incumbent)",
    "M7": "FINAL tree, clean paired batch: RB = documented rollback (= frozen B0), D = accepted default",
    "M10": "FINAL tree, opt-in coverage floor 0.25",
    "FRprod": "frontier batch, tree ctl4", "FRcov25": "frontier batch, tree ctl4, coverage floor",
    "FRcov30": "frontier batch, tree ctl4, coverage floor", "FRcov35": "frontier batch, tree ctl4, coverage floor",
    "FRlex0": "frontier batch, lexicographic staging (experimental)",
    "FRlex5": "frontier batch, lexicographic staging (experimental)",
    "FRlex10": "frontier batch, lexicographic staging (experimental)",
}
lines += ["## A. Controlled global-stage runs (same pool and budget per seed; regional hints absent)", "",
          "Batch notes: " + "; ".join(f"**{k}** {v}" for k, v in NOTES.items()), "",
          "| tag | seed | variant | solver | TL s | solution | profit M | revenue M | cost M | margin % | served TEU | "
          "coverage % | svc | vessels | load factor | paths | vars | gap to bound % | flow re-opt gain M | "
          "ledger viol. | reconciled | pool hash | path hash | file |",
          "|---|---:|---|---|---:|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|---|---|---|"]
for r in sorted(ctl, key=lambda x: (x["tag"], x["variant"], x["seed"])):
    lines.append(
        f"| {r['tag']} | {r['seed']} | {r['variant']} | {r['solver']} | {r['tl']:.0f} | {r['sol']} | {m(r['profit'])} | "
        f"{m(r['rev'], 1)} | {m(r['cost'], 1)} | {pct(r['margin'])} | "
        f"{num(r['teu'])} | {pct(r['cov'])} | {r['svc']} | {r['ves']} | "
        f"{num(r['lf'], '.3f')} | {r['paths']} | {r['vars']} | {pct(r['gap'])} | "
        f"{m(r['reopt'])} | {r['viol']} | {r['recon']} | {r['pool']} | {r['pathsha']} | {r['file']} |")
lines.append("")

# per (tag, variant) statistics
lines += ["### A.1 Per tag and variant: mean (sd) over seeds, paired difference against the tag's baseline variant (`B0`, else `RB`; frontier batches: `FRprod`)", "",
          "| tag | variant | n | profit M mean (sd) | min .. max | Δ vs the tag's baseline variant (B0 / RB / FRprod; paired) | seeds better | coverage % mean | "
          "served TEU mean | cost M mean | margin % mean | services mean | vessels mean | load factor mean | viol. | recon. |",
          "|---|---|---:|---:|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
by = {}
for r in ctl:
    by.setdefault((r["tag"], r["variant"]), {})[r["seed"]] = r
for (tag, var), rows in sorted(by.items()):
    base_name = next((b for b in ("B0", "RB") if (tag, b) in by), "B0")
    base = by.get((tag, base_name), {})
    if tag.startswith("FR"):                      # frontier batches: one tag per strategy, variant "R"
        base = by.get(("FRprod", "R"), {})
    seeds = sorted(rows)
    pr = [rows[s]["profit"] for s in seeds if rows[s]["profit"] is not None]
    if not pr:
        continue
    paired = [rows[s]["profit"] - base[s]["profit"] for s in seeds
              if s in base and base[s]["profit"] is not None and rows[s]["profit"] is not None]

    def mean(k):
        v = [rows[s][k] for s in seeds if rows[s][k] is not None]
        return statistics.mean(v) if v else float("nan")
    lines.append(
        f"| {tag} | {var} | {len(pr)} | {statistics.mean(pr) / 1e6:.2f} ({(statistics.pstdev(pr) / 1e6 if len(pr) > 1 else 0):.2f}) | "
        f"{min(pr) / 1e6:.2f} .. {max(pr) / 1e6:.2f} | "
        f"{(statistics.mean(paired) / 1e6 if paired else float('nan')):+.2f} | "
        f"{sum(1 for x in paired if x > 0)}/{len(paired)} | {mean('cov'):.1f} | {mean('teu'):,.0f} | "
        f"{mean('cost') / 1e6:.1f} | {mean('margin'):.1f} | {mean('svc'):.1f} | {mean('ves'):.0f} | "
        f"{mean('lf'):.3f} | {sum(rows[s]['viol'] for s in seeds)} | "
        f"{sum(1 for s in seeds if rows[s]['recon'])}/{len(seeds)} |")
lines.append("")

# ----------------------------------------------------------------------------- B: iterations
its = []
for f in sorted(glob.glob(str(EV / "outputs" / "*.json"))):
    try:
        d = json.loads(Path(f).read_text(encoding="utf-8"))
    except Exception:                                                  # noqa: BLE001
        continue
    if isinstance(d, dict) and "iterations" in d and "runs" in d:
        its.append((Path(f).stem, d))
if its:
    lines += ["## B. Iteration-structured controlled runs (3 iterations per seed, best verified iteration)", "",
              "| file | seed | env | iteration profits M | feedback elites | best iteration | best profit M | "
              "best coverage % | services | ledger viol. |", "|---|---:|---|---|---|---:|---:|---:|---:|---:|"]
    for name, d in its:
        runs = d["runs"]
        env = ",".join(f"{k.replace('LINER_', '')}={v}" for k, v in sorted(d.get("env", {}).items()))
        lines.append(
            f"| {name} | {d['seed']} | {env} | "
            f"{' / '.join(m(r.get('profit')) for r in runs)} | "
            f"{' / '.join(str(r.get('feedback_elites')) for r in runs)} | "
            f"{(d.get('best') or {}).get('iteration')} | {m((d.get('best') or {}).get('profit'))} | "
            f"{pct((d.get('best') or {}).get('coverage_pct'))} | {(d.get('best') or {}).get('services')} | "
            f"{sum(r.get('violations') or 0 for r in runs)} |")
    lines.append("")

# ----------------------------------------------------------------------------- C: orchestrator
lines += ["## C. End-to-end orchestrator runs (`tests/test_orchestrator.py`; unseeded; regional hints; LLM 429s ignored)", "",
          "| label | exit | assertions | profit M | margin % | coverage % | services | vessels | iteration | status | "
          "ledger verified | violations | milp status | flow re-opt gain M | direct / feeder / hub / multi-hop TEU | "
          "load factor | env | elapsed s |",
          "|---|---:|---|---:|---:|---:|---:|---:|---:|---|---|---:|---|---:|---|---:|---|---:|"]
orch = []
for f in sorted(glob.glob(str(EV / "runs" / "*.pipeline_output.json"))):
    label = Path(f).name.replace(".pipeline_output.json", "")
    if label.startswith("T19S_"):          # copies of an orchestrator run's output made by the suite runs
        continue
    meta = EV / "runs" / f"{label}.meta.txt"
    mt = meta.read_text(encoding="utf-8") if meta.exists() else ""
    ex = re.search(r"exit_code: (\d+)", mt)
    el = re.search(r"elapsed_s: (\d+)", mt)
    env = re.search(r"env: (\{.*\})", mt)
    try:
        d = json.loads(Path(f).read_text(encoding="utf-8"))
    except Exception:                                                  # noqa: BLE001
        continue
    nl = d.get("network_ledger") or {}
    w = nl.get("weekly_usd") or {}
    sc = d.get("test_scorecard") or {}
    sr = nl.get("strategy_report") or {}
    bs = sr.get("by_strategy") or {}
    shares = " / ".join(f"{bs[k]['served_teu']:,.0f}" for k in ("direct", "feeder", "hub_and_spoke", "multi_hop")
                        if k in bs) if bs else ""
    fr = ((nl.get("optimality") or {}).get("flow_reoptimisation") or {})
    prof = w.get("operating_profit")
    lf_orch = ""
    if sr.get("available"):
        lf_orch = num(((sr.get("utilisation") or {}).get("network") or {}).get("load_factor"), ".3f")
    lines.append(
        f"| {label} | {ex.group(1) if ex else ''} | {sc.get('assertions_passed')}/{sc.get('assertions_total')} | "
        f"{m(prof)} | {pct((w.get('profit_margin_on_revenue') or 0) * 100)} | "
        f"{pct((nl.get('demand_teu_per_week') or {}).get('coverage_pct'))} | "
        f"{(nl.get('services') or {}).get('operated')} | "
        f"{sum(v.get('used', 0) for v in (nl.get('fleet_by_class') or {}).values())} | "
        f"{d.get('final_selected_iteration')} | {d.get('status')} | {nl.get('verified')} | "
        f"{len(nl.get('violations') or [])} | {(nl.get('optimality') or {}).get('milp_status')} | "
        f"{m(fr.get('gain_usd')) if fr.get('applied') else ''} | {shares} | "
        f"{lf_orch} | "
        f"{env.group(1) if env else ''} | {el.group(1) if el else ''} |")
    orch.append({"label": label, "profit": prof, "file": Path(f).name})
lines.append("")

(REPORT / "results_matrix.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("wrote", REPORT / "results_matrix.md", "controlled rows:", len(ctl), "iteration files:", len(its),
      "orchestrator runs:", len(orch))
