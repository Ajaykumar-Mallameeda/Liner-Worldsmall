"""Markdown tables of the Tier-0 consumer execution (backend + frontend + decision layer).

usage: python -I build_tier0_table.py <backend.json> <frontend.json> <decision_layer.json> <out.md>
"""
import json
import sys
from pathlib import Path

be = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
fe = json.loads(Path(sys.argv[2]).read_text(encoding="utf-8"))
dl = json.loads(Path(sys.argv[3]).read_text(encoding="utf-8"))
OUT = Path(sys.argv[4])

order = ["real", "derived_margin_just_below_15", "derived_margin_exactly_15", "derived_margin_exactly_20",
         "derived_margin_exactly_25", "derived_loss_minus_5", "derived_zero_revenue",
         "derived_ledger_not_verified", "derived_margin_fields_missing"]


def f(v, nd=1):
    if v is None:
        return "none"
    if isinstance(v, (int, float)):
        return f"{v:.{nd}f}"
    return str(v)


L = ["# Tier-0 consumer execution — generated tables", "",
     "Generated by `evidence/tools/build_tier0_table.py` from `evidence/outputs/tier0_backend_responses.json`, "
     "`tier0_frontend_render.json` and the decision-layer record of `tier0_scenarios.py`.  `real` is an unmodified "
     "orchestrator output (`T19B0_orch_run1`); every `derived_*` scenario starts from it and changes only the "
     "margin-driving numbers, with the verdict text regenerated by the production decision layer.", "",
     "## Backend (`backend/server.py` REST path and `backend/routes/metrics.py`)", "",
     "| scenario | decision layer (label · margin text · band) | ledger margin | `/api/metrics/summary` margin | "
     "`/api/regions/` margins | `routes/metrics.py` margin | backend status |",
     "|---|---|---:|---:|---|---:|---|"]
for name in order:
    s = be["scenarios"].get(name)
    if s is None:
        continue
    d = dl[name]
    mt = s["endpoints"]["/api/metrics/summary"]["body"]
    mets = mt.get("metrics", {})
    regs = s["endpoints"]["/api/regions/"]["body"]["regions"]
    L.append(f"| {name} | {d['decision_layer_label']} · {d['decision_layer_margin_text']} · {d['decision_layer_band']} | "
             f"{f((s['decision_layer']['ledger_margin'] or 0) * 100 if s['decision_layer']['ledger_margin'] is not None else None)} | "
             f"{f(mets.get('margin'), 2)} | {', '.join(f(v.get('margin')) for v in regs.values())} | "
             f"{f(s.get('routes_metrics_profit_margin'), 2)} | {(mt.get('status') or {}).get('status')} |")
L += ["", "## Frontend (runtime adapter + React components, server-side rendered)", "",
      "| scenario | decision-layer verdict | adapter global margin | SummaryView verdict · margin sentence | "
      "RegionCard margins | RegionalIntelligence | OptimizationInsights | ExportPanel | console verdict card | benchmark badge (target 20 %, component unreferenced) |",
      "|---|---|---:|---|---|---|---|---|---|---|"]
for name in order:
    s = fe["scenarios"].get(name)
    if s is None:
        continue
    c = s["components"]
    sv = c.get("SummaryView", {})
    rc = c.get("RegionCard", {})
    cards = ", ".join((v["margin_cell"].replace("|", " ").replace("Margin", "").strip() if v.get("ok")
                       else "**CRASH** " + v["error"].split(":")[0]) for v in rc.values())
    ri = c.get("RegionalIntelligence", {})
    oi = c.get("OptimizationInsights", {})
    ex = c.get("ExportPanel", {})
    bb = (c.get("BenchmarkBadge_margin_target") or {}).get("badge", "")
    cc = c.get("CommandCenter") or {}
    ccv = (cc.get("verdict_card") or "").replace("EXPLANATION|", "").replace("|", " ") if cc.get("ok")         else "**CRASH** " + str(cc.get("error"))[:50]
    L.append(
        f"| {name} | {dl[name]['decision_layer_label']} | {f(s['normalized'].get('global_margin'), 2)} | "
        f"{sv.get('verdict') if sv.get('ok') else '**CRASH** ' + str(sv.get('error'))} · "
        f"{(sv.get('margin_sentence') or '').replace('|', ' ').strip() if sv.get('ok') else ''} | {cards} | "
        f"{(ri.get('margin_cell') or '').replace('|', ' ') if ri.get('ok') else '**CRASH** ' + str(ri.get('error'))[:50]} | "
        f"{(oi.get('best_margin') or '').replace('|', ' ') if oi.get('ok') else '**CRASH** ' + str(oi.get('error'))[:50]} | "
        f"{(ex.get('margin_row') or '').replace('|', ' ') if ex.get('ok') else '**CRASH** ' + str(ex.get('error'))[:50]} | "
        f"{ccv} | {bb.replace('|', ' ').strip()} |")
OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
print("wrote", OUT)
