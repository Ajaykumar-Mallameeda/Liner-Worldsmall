"""Tier-0 consumer check, scenario builder.

Writes one pipeline-output-shaped JSON per scenario into ``<out_dir>``.  ``real`` is a REAL
orchestrator output copied unchanged.  Every ``derived_*`` scenario starts from that real output
and changes ONLY the margin-driving numbers (revenue / cost / profit of the network, its regions
and the ledger block) so that the margin takes the edge value being tested; the verdict text of
each scenario (executive summary header and regional explanations) is then REGENERATED by the
production decision-layer code (``OrchestratorAgent._margin_report`` /
``_rule_based_explanation``), so a consumer is tested against the verdict the pipeline would
actually emit for those numbers.  Derived scenarios test consumer handling of an edge value; they
are not evidence about the optimiser.

usage: python -I tier0_scenarios.py <tree_root> <real_pipeline_output.json> <out_dir>
"""
import copy
import json
import sys
from pathlib import Path

ROOT, REAL, OUT = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
sys.path.insert(0, str(ROOT))
OUT.mkdir(parents=True, exist_ok=True)

from src.agents.orchestrator_agent import OrchestratorAgent          # noqa: E402

real = json.loads(REAL.read_text(encoding="utf-8"))


def with_margin(d, m):
    """Scale costs so that the network (and every region) has margin ``m`` at unchanged revenue."""
    d = copy.deepcopy(d)
    w = d["network_ledger"]["weekly_usd"]
    rev = w["revenue"]
    cost0 = w["total_operating_cost"]
    k = (1.0 - m) * rev / cost0 if cost0 else 0.0
    for key in ("vessel_cost", "fuel_cost", "port_call_fixed_cost", "handling_cost",
                "transshipment_cost", "port_variable_cost", "total_operating_cost"):
        w[key] = w[key] * k
    w["operating_profit"] = rev * m
    w["profit_margin_on_revenue"] = m if rev > 0 else None
    sm = d["summary_metrics"]
    sm["weekly_profit"], sm["annual_profit"] = rev * m, rev * m * 52
    for key in ("cost", "total_cost", "operating_cost", "transship_cost", "port_cost", "fuel_cost"):
        if key in sm and isinstance(sm[key], (int, float)):
            sm[key] = sm[key] * k
    for r in d["regional_results"]:
        rrev = (r.get("weekly_profit", 0) or 0) + (r.get("total_cost", 0) or 0)
        for key in ("operating_cost", "fuel_cost", "transship_cost", "port_cost"):
            if isinstance(r.get(key), (int, float)):
                r[key] = r[key] * k              # vessel hire sum must equal the ledger's vessel_cost
        r["total_cost"] = rrev * (1.0 - m)
        r["weekly_profit"] = rrev * m
        r["profit_margin_pct"] = round(m * 100.0, 1) if rrev > 0 else 0
    return d


def regenerate_verdict_text(d):
    """Executive-summary header and regional explanations from the production decision layer."""
    regs = d["regional_results"]
    mr = OrchestratorAgent._margin_report(regs, d["network_ledger"])
    cov = d["network_ledger"]["demand_teu_per_week"]["coverage_pct"]
    head = (f"Verdict: {mr['label']}\n  Profit margin {mr['margin_text']} with {cov:.1f}% demand coverage.\n"
            f"{mr['advisory_line']}")
    body = d["executive_summary"].split("\n\nStrengths:", 1)
    d["executive_summary"] = head.rstrip("\n") + "\n\nStrengths:" + (body[1] if len(body) > 1 else "\n")
    for r in regs:
        r["explanation"] = OrchestratorAgent._rule_based_explanation(r)
    # the decision layer's own margin fields, from the production functions (a consumer reads them)
    from src.network.metrics import canonical_network_economics, classify_margin
    econ = canonical_network_economics(regs, d["network_ledger"])
    gm = d["decision_output"]["global_metrics"]
    gm.update(revenue=econ["revenue"], total_profit=econ["profit"], total_cost=econ["total_cost"],
              profit_margin_pct=econ["profit_margin_pct"], accounting_status=econ["accounting_status"],
              accounting_verified=econ["accounting_verified"], accounting_issues=econ["accounting_issues"])
    d["decision_output"].setdefault("evaluation", {})["margin_verdict"] = classify_margin(
        econ["profit_margin_pct"], econ["accounting_verified"])
    return d, mr


scen = {"real": copy.deepcopy(real)}
for name, m in (("derived_margin_exactly_15", 0.15), ("derived_margin_exactly_20", 0.20),
                ("derived_margin_exactly_25", 0.25), ("derived_margin_just_below_15", 0.1499),
                ("derived_loss_minus_5", -0.05)):
    scen[name] = with_margin(real, m)
z = with_margin(real, 0.0)
w = z["network_ledger"]["weekly_usd"]
for key in ("revenue", "vessel_cost", "fuel_cost", "port_call_fixed_cost", "handling_cost",
            "transshipment_cost", "port_variable_cost", "total_operating_cost", "operating_profit"):
    w[key] = 0.0
w["profit_margin_on_revenue"] = None
z["summary_metrics"].update({"revenue": 0.0, "weekly_profit": 0.0, "annual_profit": 0.0, "cost": 0.0,
                             "total_cost": 0.0})
for r in z["regional_results"]:
    r["weekly_profit"], r["total_cost"], r["profit_margin_pct"] = 0.0, 0.0, 0
    for key in ("operating_cost", "fuel_cost", "transship_cost", "port_cost"):
        if isinstance(r.get(key), (int, float)):
            r[key] = 0.0
scen["derived_zero_revenue"] = z
u = copy.deepcopy(real)
u["status"] = "incomplete_accounting"
u["network_ledger"]["verified"] = False
scen["derived_ledger_not_verified"] = u
mk = copy.deepcopy(real)
for r in mk["regional_results"]:
    r.pop("profit_margin_pct", None)
for key in ("profit_margin", "profit_margin_pct"):
    mk["summary_metrics"].pop(key, None)
mk["summary_metrics"].pop("revenue", None)           # the frontend derives the margin from revenue
scen["derived_margin_fields_missing"] = mk

meta = {}
for name, d in scen.items():
    if name != "real":
        d, mr = regenerate_verdict_text(d)
    else:
        mr = OrchestratorAgent._margin_report(d["regional_results"], d["network_ledger"])
    meta[name] = {"decision_layer_label": mr["label"], "decision_layer_band": mr["verdict"]["band"],
                  "decision_layer_margin_pct": mr["verdict"]["margin_pct"],
                  "decision_layer_margin_text": mr["margin_text"],
                  "regional_verdict_lines": {r["region"]: (r.get("explanation") or "").splitlines()[0]
                                             for r in d["regional_results"]}}
    (OUT / f"{name}.json").write_text(json.dumps(d), encoding="utf-8")
(OUT / "_decision_layer.json").write_text(json.dumps(meta, indent=1), encoding="utf-8")
print(json.dumps({k: (v["decision_layer_band"], v["decision_layer_label"], v["decision_layer_margin_text"])
                  for k, v in meta.items()}, indent=1))
