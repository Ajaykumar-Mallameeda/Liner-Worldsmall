"""Write reports/campaign_20261012_1815/INDEX.md: every deliverable and key evidence file with its SHA-256, and
the map from each conclusion to the artifacts that carry it.  Does not overwrite an existing INDEX.md unless INDEX_OVERWRITE is set (writes
INDEX_<n>.md instead).

usage: python -I make_index.py
"""
import hashlib
import json
from pathlib import Path

