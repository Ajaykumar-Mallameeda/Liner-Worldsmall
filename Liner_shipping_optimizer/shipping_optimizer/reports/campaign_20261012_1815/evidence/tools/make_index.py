EV = CAMP / "evidence"


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def row(p: Path, base: Path = CAMP) -> str:
    if not p.exists():
        return f"| `{p.relative_to(base).as_posix()}` | MISSING | |"
    return f"| `{p.relative_to(base).as_posix()}` | `{sha(p)[:16]}…` | {p.stat().st_size:,} |"


