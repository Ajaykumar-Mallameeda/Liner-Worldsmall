"""Task 17 / R2: full-pipeline (orchestrator) reproducibility.  Compares, run against run, what the stochastic
components produced BEFORE the global solve and what the global stage returned.

usage: python -I r2_compare.py <out.md> <group>=<prefix> [<group>=<prefix> ...]
  prefix selects evidence/runs/<prefix>*_run<k>.pipeline_output.json   (runs of one group are compared pairwise)

Per run / iteration / region: services generated, services kept by the regional filter, GA generations executed, GA best
fitness (rounded), a hash of the region's selected-service set (ports, class, frequency).  Per run: the global stage's
selected-service hash and profit per iteration.  A group is "identical" on a quantity when every run of the group gives
the same value for every iteration and region.
"""
import hashlib
import json
import sys
from pathlib import Path

RUNS = Path(r"C:\Users\WINDOWS\Liner-Worldsmall\Liner_shipping_optimizer\shipping_optimizer\reports\campaign_20261012_1815\evidence\runs")
out = Path(sys.argv[1])
groups = [a.split("=", 1) for a in sys.argv[2:]]


def h(obj) -> str:
    return hashlib.sha256(json.dumps(obj, sort_keys=True, default=str).encode()).hexdigest()[:10]


def summarise(po: Path):
    d = json.loads(po.read_text(encoding="utf-8"))
    its = []
    for it in d.get("iteration_results", []):
        regs = {}
        for r in it.get("regional_results", []):
            sel = sorted((tuple(s.get("ports", [])), s.get("vessel_class"), s.get("frequency_per_week")) for s in r.get("selected_services", []))
            ga = r.get("ga_telemetry") or {}
            regs[r.get("region")] = {
                "generated": r.get("services_generated"), "filtered": r.get("services_filtered"),
                "selected": r.get("services_selected"), "gens": ga.get("actual_generations_executed"),
                "fit": round(ga.get("best_fitness"), 6) if isinstance(ga.get("best_fitness"), (int, float)) else None,
                "sel_hash": h(sel)}
        nl = it.get("network_ledger") or {}
        plan = sorted((tuple(s.get("ports", [])), s.get("vessel_class"), s.get("frequency_per_week")) for s in (nl.get("plan") or {}).get("services", []))
        its.append({"regions": regs, "global_hash": h(plan),
                    "profit": round((nl.get("weekly_usd") or {}).get("operating_profit") or 0.0, 2)})
    return {"selected_iteration": d.get("final_selected_iteration"), "its": its,
            "runtime": (d.get("summary_metrics") or {}).get("total_runtime")}


lines = ["# Task 17 / R2 — orchestrator runs compared (generated by `evidence/tools/r2_compare.py`)", ""]
for name, prefix in groups:
    files = sorted(RUNS.glob(f"{prefix}*.pipeline_output.json"))
    runs = [(f.name.replace(".pipeline_output.json", ""), summarise(f)) for f in files]
    lines += [f"## {name}  (`{prefix}*`, {len(runs)} runs)", ""]
    if not runs:
        lines += ["no runs found", ""]
        continue
    n_it = min(len(r["its"]) for _, r in runs)
    lines += ["| run | iteration | " + " | ".join(f"{reg} gen/filt/sel/gens/fit/hash" for reg in sorted(runs[0][1]["its"][0]["regions"])) + " | global plan hash | profit USD/wk |",
              "|---|---:|" + "---|" * (len(runs[0][1]["its"][0]["regions"]) + 2)]
    for rn, r in runs:
        for i, it in enumerate(r["its"]):
            cells = []
            for reg in sorted(runs[0][1]["its"][0]["regions"]):
                x = it["regions"].get(reg, {})
                cells.append(f"{x.get('generated')}/{x.get('filtered')}/{x.get('selected')}/{x.get('gens')}/{x.get('fit')}/{x.get('sel_hash')}")
            lines.append(f"| {rn} | {i} | " + " | ".join(cells) + f" | {it['global_hash']} | {it['profit']:,.0f} |")

    def same(fn):
        vals = [tuple(fn(r["its"][i]) for i in range(n_it)) for _, r in runs]
        return all(v == vals[0] for v in vals)
    regs = sorted(runs[0][1]["its"][0]["regions"])
    lines += ["", f"* counts generated / filtered identical across runs, all iterations: **{same(lambda it: tuple((it['regions'][g]['generated'], it['regions'][g]['filtered']) for g in regs))}**",
              f"* regional selected-service sets identical: **{same(lambda it: tuple(it['regions'][g]['sel_hash'] for g in regs))}**",
              f"* GA generations / best fitness identical: **{same(lambda it: tuple((it['regions'][g]['gens'], it['regions'][g]['fit']) for g in regs))}**",
              f"* global plan (service, class, frequency) identical: **{same(lambda it: (it['global_hash'],))}**",
              f"* global profit identical: **{same(lambda it: (it['profit'],))}**", ""]
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print("written", out)
