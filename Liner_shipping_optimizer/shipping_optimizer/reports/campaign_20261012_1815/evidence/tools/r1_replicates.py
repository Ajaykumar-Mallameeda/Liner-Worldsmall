"""Task 17 / R1: replicate noise of the controlled global stage under IDENTICAL load.

usage: python -I r1_replicates.py <out.md>
Reads R1_baseA / R1_baseB / R1_finA / R1_finB (same configuration twice per pair, all four run concurrently per seed).
For each pair and seed: pool hash, path-pool hash, model size, MILP dual bound, profit A / B, difference, served TEU, services.
"""
import json
import statistics as st
import sys
from pathlib import Path

OUT = Path(r"C:\Users\WINDOWS\Liner-Worldsmall\Liner_shipping_optimizer\shipping_optimizer\reports\campaign_20261012_1815\evidence\outputs")
out = Path(sys.argv[1])


def load(tag, s):
    p = OUT / f"{tag}_seed{s}.json"
    if not p.exists():
        return None
    d = json.loads(p.read_text(encoding="utf-8"))
    r = (d.get("runs") or [None])[-1]
    if not r or not r.get("ok"):
        return None
    rec = (r.get("ledger") or {}).get("reconciliation") or {}
    return {"pool": (d.get("pool") or {}).get("regional_pool_sha256"), "paths": r.get("path_pool_sha256"),
            "profit": r["ledger"]["profit"], "served": r["ledger"]["served_teu"], "svc": r["ledger"]["services"],
            "bound": rec.get("relaxation_upper_bound"), "int_services": rec.get("services_in_integer_problem"),
            "raw": rec.get("milp_profit_before_penalty")}


L = ["# Task 17 / R1 — replicate noise under identical load (generated by `evidence/tools/r1_replicates.py`)", "",
     "Each seed: four processes run concurrently — two copies of the default configuration (`baseA`, `baseB`) and two copies of the final",
     "candidate (`finA`, `finB`).  A pair has identical code, inputs, environment, seed and machine load pattern; any difference is the",
     "time-limited incumbent of CBC (wall-clock), not the model.", ""]
for name, a, b in (("default", "R1_baseA", "R1_baseB"), ("final candidate", "R1_finA", "R1_finB")):
    L += [f"## {name}", "", "| seed | pool hash equal | path-set hash equal | integer-problem size equal | dual bound equal | profit A M | profit B M | |Δ| M | served TEU A / B | services A / B |",
          "|---:|---|---|---|---|---:|---:|---:|---|---|"]
    diffs = []
    for s in range(5):
        x, y = load(a, s), load(b, s)
        if not x or not y:
            L.append(f"| {s} | – | – | – | – | – | – | – | – | – |")
            continue
        d = abs(x["profit"] - y["profit"]) / 1e6
        diffs.append(d)
        L.append(f"| {s} | {x['pool'] == y['pool']} | {x['paths'] == y['paths']} | {x['int_services'] == y['int_services']} | "
                 f"{x['bound'] == y['bound']} | {x['profit'] / 1e6:.2f} | {y['profit'] / 1e6:.2f} | {d:.2f} | "
                 f"{x['served']:,.0f} / {y['served']:,.0f} | {x['svc']} / {y['svc']} |")
    if diffs:
        L += ["", f"* identical plan (|Δ| < 1 USD) on {sum(1 for d in diffs if d < 1e-6)} of {len(diffs)} seeds; "
                  f"mean |Δ| {st.mean(diffs):.2f} M, max {max(diffs):.2f} M", ""]
out.write_text("\n".join(L) + "\n", encoding="utf-8")
print("\n".join(L))
