"""Phase 6 sensitivity table: for each scenario (a copy of the final tree with ONE assumption changed) the default
configuration ("base") and the final candidate ("fin") on seeds 0-2, run concurrently within the scenario group.

usage: python -I s3_table.py <out.md>
Reference rows come from batch D5 (seeds 0-2, arms base / e = final candidate, production assumptions).
"""
import json
import statistics as st
import sys
from pathlib import Path

OUT = Path(r"C:\Users\WINDOWS\Liner-Worldsmall\Liner_shipping_optimizer\shipping_optimizer\reports\campaign_20261012_1815\evidence\outputs")
out = Path(sys.argv[1])
SEEDS = (0, 1, 2)
SCEN = [("reference (production assumptions)", "D5_base", "D5_e"),
        ("S1 revised TransitTime (upstream file)", "S1_base", "S1_fin"),
        ("S2 Capacity FFE x 2", "S2_base", "S2_fin"),
        ("S3a port stay 12 h", "S3a_base", "S3a_fin"),
        ("S3b port stay 48 h", "S3b_base", "S3b_fin"),
        ("S4a transfer wait 1.75 d", "S4a_base", "S4a_fin"),
        ("S4b transfer wait 7.0 d", "S4b_base", "S4b_fin"),
        ("B400 bunker 400 USD/t", "B400_base", "B400_fin"),
        ("B1000 bunker 1000 USD/t", "B1000_base", "B1000_fin")]


def load(tag, s):
    p = OUT / f"{tag}_seed{s}.json"
    if not p.exists():
        return None
    d = json.loads(p.read_text(encoding="utf-8"))
    r = (d.get("runs") or [None])[-1]
    if not r:
        return None
    if not r.get("ok"):
        return {"unsolved": True, "status": r.get("status")}
    led = r["ledger"]
    rr = r.get("regional_reconciliation") or {}
    return {"profit": led["profit"] / 1e6, "cov": led["coverage_pct"], "svc": led["services"], "ves": led["vessels"],
            "ok": led.get("valid") is True and not (led.get("violations") or []) and rr.get("accounting_verified") is True,
            "demand": led["total_demand_teu"]}


L = ["# Phase 6 — sensitivity of the conclusion to the unverified assumptions (generated by `evidence/tools/s3_table.py`)", "",
     "Seeds 0 – 2; per scenario the default (`base`) and the final candidate (`fin` = C1 + LS + 10 % class variants) run **concurrently** on the",
     "scenario tree.  Profit is the independent ledger's, **under that scenario's assumption** — levels are not comparable across rows, the",
     "*difference* between the two configurations within a row is the quantity of interest.", "",
     "| scenario | n paired | no plan at 120 s (base / fin) | base profit M/wk | fin profit M/wk | Δ M (fin − base) | seeds higher | base cov % | fin cov % | Δ cov pp | base svc / ves | fin svc / ves | gates (ledger, 0 viol, regional) |",
     "|---|---:|---|---:|---:|---:|---:|---:|---:|---:|---|---|---|"]
for name, tb, tf in SCEN:
    allrows = [(load(tb, s), load(tf, s)) for s in SEEDS]
    unsolved_b = sum(1 for b, f in allrows if b and b.get("unsolved"))
    unsolved_f = sum(1 for b, f in allrows if f and f.get("unsolved"))
    rows = [(b, f) for b, f in allrows if b and f and not b.get("unsolved") and not f.get("unsolved")]
    if not rows:
        L.append(f"| {name} | 0 | {unsolved_b} / {unsolved_f} | – | – | – | – | – | – | – | – | – | – |")
        continue
    bp = st.mean(b["profit"] for b, _ in rows)
    fp = st.mean(f["profit"] for _, f in rows)
    pos = sum(1 for b, f in rows if f["profit"] > b["profit"])
    ok = sum(1 for b, f in rows if b["ok"]) + sum(1 for _, f in rows if f["ok"])
    L.append(f"| {name} | {len(rows)} | {unsolved_b} / {unsolved_f} | {bp:.2f} | {fp:.2f} | {fp - bp:+.2f} | {pos}/{len(rows)} | "
             f"{st.mean(b['cov'] for b, _ in rows):.1f} | {st.mean(f['cov'] for _, f in rows):.1f} | "
             f"{st.mean(f['cov'] - b['cov'] for b, f in rows):+.1f} | "
             f"{st.mean(b['svc'] for b, _ in rows):.0f} / {st.mean(b['ves'] for b, _ in rows):.0f} | "
             f"{st.mean(f['svc'] for _, f in rows):.0f} / {st.mean(f['ves'] for _, f in rows):.0f} | {ok}/{2 * len(rows)} |")
L.append("")
L.append("Per-seed profits (M/wk, base → fin):")
L.append("")
L.append("| scenario | seed 0 | seed 1 | seed 2 |")
L.append("|---|---|---|---|")
for name, tb, tf in SCEN:
    cells = []
    for s in SEEDS:
        b, f = load(tb, s), load(tf, s)
        if b and f and not b.get("unsolved") and not f.get("unsolved"):
            cells.append(f"{b['profit']:.2f} → {f['profit']:.2f}")
        elif b and f:
            cells.append(("base: no plan" if b.get("unsolved") else f"{b['profit']:.2f}") + " → " +
                         ("fin: no plan" if f.get("unsolved") else f"{f['profit']:.2f}"))
        else:
            cells.append("–")
    L.append(f"| {name} | " + " | ".join(cells) + " |")
out.write_text("\n".join(L) + "\n", encoding="utf-8")
print("\n".join(L))
