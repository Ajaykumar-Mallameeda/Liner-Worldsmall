#!/usr/bin/env python3
"""Write PROVENANCE_REPORT.md from the dataset manifests: what is source-derived and what is synthetic.

    python scripts/multi_dataset/build_provenance_report.py
Everything (paths, hashes, counts, validation results) is read from ``data/datasets/*_manifest.json`` and the
generation manifests; the report is regenerated, never hand-edited.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from src.data.dataset_registry import list_datasets, sha256_file          # noqa: E402

OUT = ROOT / "reports" / "multi_dataset_20261016" / "PROVENANCE_REPORT.md"
ZIP = Path("C:/Users/WINDOWS/Downloads/LINERLIB-master (1).zip")


def main() -> int:
    L = ["# Provenance report: source-derived versus synthetic inputs\n",
         "Generated by `scripts/multi_dataset/build_provenance_report.py` from `data/datasets/*_manifest.json` "
         "(regenerate, do not edit).\n"]
    if ZIP.is_file():
        L.append(f"LINERLIB archive used: `{ZIP.name}` sha256 `{sha256_file(ZIP)}`; the repository copy "
                 f"`data/LINERLIB-master` was verified byte-for-byte against it (76 files, 0 differences).\n")
    L.append("| dataset | kind | what is real | what is derived or synthetic |\n|---|---|---|---|")
    L.append("| WorldSmall | real (LINERLIB) | every input file, unchanged since the C3 baseline | none; its canonical JSON is built from the files by the loader |")
    L.append("| baltic, WAF | real (LINERLIB) | demand, regional fleet and every port row are verbatim source rows; distances are source records | port set derived from the source demand (as WorldSmall); `fleet_data.csv` holds the source rows of the classes the regional fleet uses; one distance record per directed pair selected by the verified WorldSmall rule (first listed = shortest); alternatives kept |")
    L.append("| World-500, World-1000 | **synthetic** | `fleet_data.csv` (class table, byte copy); the calibration statistics are measured on real LINERLIB | every port, coordinate, cost, distance, OD, volume, rate, transit limit and fleet quantity is generated (seed 20261016) |\n")
    for s in list_datasets():
        m = json.loads(s.manifest_path.read_text(encoding="utf-8"))
        L.append(f"## {s.key}  ({s.kind})\n")
        L.append(f"- source directory: `{m['source_package']['dir']}`")
        L.append(f"- canonical JSON: `{m['problem_json']['path']}`  sha256 `{m['problem_json']['sha256']}`  ({m['problem_json']['bytes']:,} bytes)")
        L.append(f"- manifest: `{s.manifest_path.relative_to(ROOT).as_posix()}`;  schema `{m['schema']['name']}` v{m['schema']['version']};  "
                 f"converter {m['schema']['converter_version']};  build id `{m['schema']['build_id'][:16]}…`")
        L.append(f"- output directory (default): `{m['output_dir']}`" + ("  (WorldSmall keeps its legacy locations unless `--output-dir` is given)" if s.legacy_outputs else ""))
        c, t = m["counts"], m["totals"]
        L.append(f"- counts: {c['ports']} ports; {c['demand_records']} demand records ({c['unique_od_pairs']} unique OD pairs); "
                 f"{c['directed_distance_pairs']:,} directed distance pairs ({c['pairs_with_distance_alternatives']} with alternatives, "
                 f"{c['distance_records_incl_alternatives']:,} source records); {c['canal_flagged_pairs']:,} canal-flagged pairs; "
                 f"{c['pairs_with_draft_limit']} draft-limited legs; {c['fleet_classes']} classes, {c['vessels_total']:,} vessels {c['vessels_by_class']}")
        L.append(f"- totals: {t['weekly_demand_teu']:,.0f} TEU/week demand; gross revenue potential {t['weekly_gross_revenue_usd']:,.0f} USD/week")
        v = m["validation"]["summary"]
        L.append(f"- validation: {v['passed']}/{v['checks']} checks passed, {v['blocking_failures']} blocking failures, {v['warnings']} warnings")
        for chk in m["validation"]["checks"]:
            if not chk["ok"]:
                L.append(f"  - {chk['severity'].upper()}: {chk['check']}: {chk['detail']}")
        if m.get("shared_references"):
            for r in m["shared_references"]:
                L.append(f"- shared reference (route alternatives only; identified, hashed, checked against the package): `{r['path']}` sha256 `{r['sha256']}`")
        L.append("- input files:")
        for role, f in m["source_package"]["files"].items():
            L.append(f"  - {role}: `{f['file']}`  sha256 `{f['sha256']}`  ({f['bytes']:,} bytes)")
        gm = s.raw_dir / "generation_manifest.json"
        if gm.is_file():
            g = json.loads(gm.read_text(encoding="utf-8"))
            L.append(f"- generation: generator {g['generator_version']}, seed {g['seed']}, numpy {g['numpy_version']}; manifest `{gm.relative_to(ROOT).as_posix()}` "
                     f"sha256 `{sha256_file(gm)}`")
            L.append(f"- fleet rule: {g['fleet_scaling']['rule']} (reference {g['fleet_scaling']['reference']['ffe_per_vessel']:.2f} FFE/week per vessel, "
                     f"{g['fleet_scaling']['reference']['vessels']} vessels); resulting {g['fleet_scaling']['vessels_total']:,} vessels")
            L.append("- calibration (measured on LINERLIB, never invented): "
                     f"{g['calibration']['anchors']} anchor ports; out-degree geometric mean {g['calibration']['out_degree_geometric_mean']:.2f}; "
                     f"reverse-OD probability {g['calibration']['reverse_od_probability']:.3f}; revenue regression "
                     f"{g['calibration']['revenue_regression']['intercept']:.3f} + {g['calibration']['revenue_regression']['slope']:.3f} ln(distance), "
                     f"residual sd {g['calibration']['revenue_regression']['residual_sd']:.3f}")
            L.append("- diagnostics: " + ", ".join(f"{k}={g['diagnostics'][k]:.4g}" for k in
                                                   ("od_density", "mean_out_degree", "weekly_ffe", "triangle_violation_rate_sampled",
                                                    "ods_direct_sailing_feasible_at_14kn", "min_geodesic_ratio")))
            L.append("- limitations:")
            for x in g["limitations"]:
                L.append(f"  - {x}")
        L.append("")
    L.append("## Source-data defects found (reported, not corrected)\n")
    L.append("- `ports.csv` of LINERLIB places **Pointe Noire (CGPNR)** at lat 1.5468 / lon 15.7968 and **Manzanillo (PAMIT)** at lat 9.35 / lon -79.9; their routed "
             "distances are far shorter than the geodesic between the listed coordinates (min ratio ~0.3), so the coordinates (not the distances) are suspect. They only "
             "affect port clustering, not any cost or distance.")
    L.append("- The full `ports.csv` has blank draft / cost fields (127 / 145 of 435 ports) and a negative `PortCallCostFixed`; the loader rejects negatives and the synthetic "
             "generator only anchors on ports with a complete, non-negative record.")
    L.append("- `dist_dense.csv` lists several records for 18,946 directed pairs (Suez / Panama / Cape alternatives); see the route-alternative rule in `docs/MULTI_DATASET.md`.")
    L.append("- `data/datasets/worldsmall_shipping_problem.json` (legacy x2 unit convention, no fleet) and `large_shipping_problem.json` (discarded) are historical, "
             "untouched and never loaded by the dataset selection.\n")
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
